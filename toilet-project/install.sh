#!/usr/bin/env bash
# Installs or verifies what the project needs: Python 3.12 + numpy + pycairo, and FFmpeg.
# Works in Git Bash on Windows (also Linux/macOS).  Nothing is installed system-wide:
# everything goes into ./tools/ (uv + a private Python) and ./.venv/, downloaded once.
set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(pwd)"
TOOLS="$ROOT/tools"
mkdir -p "$TOOLS"

say()  { printf '\033[1;36m[install]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[install] ERROR:\033[0m %s\n' "$*"; exit 1; }

case "$(uname -s)" in
  MINGW*|MSYS*|CYGWIN*) PLATFORM=windows; EXE=".exe"; VPY=".venv/Scripts/python.exe" ;;
  Linux*)  PLATFORM=linux;  EXE=""; VPY=".venv/bin/python" ;;
  Darwin*) PLATFORM=macos;  EXE=""; VPY=".venv/bin/python" ;;
  *) die "unsupported OS" ;;
esac
say "platform: $PLATFORM"

download() {
  say "downloading $(basename "$2") ..."
  curl -fL --retry 4 --retry-delay 3 -o "$2.part" "$1" || die "download failed: $1"
  mv "$2.part" "$2"
}
unzip_to() {
  mkdir -p "$2"
  if [ "$PLATFORM" = windows ]; then
    powershell.exe -NoProfile -Command "Expand-Archive -LiteralPath '$(cygpath -w "$1")' -DestinationPath '$(cygpath -w "$2")' -Force" || die "could not extract $1"
  else
    unzip -q -o "$1" -d "$2" || die "could not extract $1"
  fi
}

# ---------------------------------------------------------------- uv + Python env
UV="$(command -v uv || true)"
[ -z "$UV" ] && [ -x "$TOOLS/uv$EXE" ] && UV="$TOOLS/uv$EXE"
if [ -z "$UV" ]; then
  case "$PLATFORM" in
    windows) download "https://github.com/astral-sh/uv/releases/latest/download/uv-x86_64-pc-windows-msvc.zip" "$TOOLS/uv.zip"
             unzip_to "$TOOLS/uv.zip" "$TOOLS"; rm -f "$TOOLS/uv.zip" ;;
    linux)   download "https://github.com/astral-sh/uv/releases/latest/download/uv-x86_64-unknown-linux-gnu.tar.gz" "$TOOLS/uv.tgz"
             tar -xzf "$TOOLS/uv.tgz" -C "$TOOLS" --strip-components=1; rm -f "$TOOLS/uv.tgz" ;;
    macos)   die "install uv first: https://docs.astral.sh/uv/ (brew install uv)" ;;
  esac
  UV="$TOOLS/uv$EXE"
fi
if [ ! -x "$VPY" ] || ! "$VPY" -c "import cairo, numpy" >/dev/null 2>&1; then
  say "creating private Python 3.12 environment (.venv) ..."
  UV_PYTHON_INSTALL_DIR="$TOOLS/python" "$UV" venv --python 3.12 .venv || die "could not create Python environment"
  "$UV" pip install --python "$VPY" -r requirements.txt || die "could not install numpy/pycairo"
fi
"$VPY" -c "import cairo, numpy; print('[install] python', __import__('sys').version.split()[0], '| pycairo', cairo.version, '| numpy', numpy.__version__)"

# ---------------------------------------------------------------- FFmpeg
find_ffmpeg() {
  if [ -n "${FFMPEG:-}" ] && [ -x "$FFMPEG" ]; then echo "$FFMPEG"; return; fi
  local c
  for c in "$TOOLS"/ffmpeg-*/bin/ffmpeg"$EXE"; do [ -x "$c" ] && { echo "$c"; return; }; done
  command -v ffmpeg 2>/dev/null || true
}
FFMPEG_BIN="$(find_ffmpeg)"
if [ -z "$FFMPEG_BIN" ]; then
  [ "$PLATFORM" = windows ] || die "ffmpeg not found - install it (apt install ffmpeg / brew install ffmpeg)"
  download "https://www.gyan.dev/ffmpeg/builds/ffmpeg-release-essentials.zip" "$TOOLS/ffmpeg.zip"
  unzip_to "$TOOLS/ffmpeg.zip" "$TOOLS"; rm -f "$TOOLS/ffmpeg.zip"
  FFMPEG_BIN="$(find_ffmpeg)"
  [ -n "$FFMPEG_BIN" ] || die "ffmpeg install failed"
fi
FFPROBE_BIN="$(dirname "$FFMPEG_BIN")/ffprobe$EXE"
[ -x "$FFPROBE_BIN" ] || FFPROBE_BIN="$(command -v ffprobe || true)"
[ -n "$FFPROBE_BIN" ] || die "ffprobe not found next to ffmpeg"
ENC="$("$FFMPEG_BIN" -hide_banner -encoders 2>/dev/null || true)"
case "$ENC" in *libx264*) ;; *) die "this ffmpeg build has no libx264 encoder" ;; esac
say "ffmpeg: $FFMPEG_BIN"

cat > "$TOOLS/env.sh" <<EOF
# generated by install.sh
export PY="$ROOT/$VPY"
export UV="$UV"
export FFMPEG="$FFMPEG_BIN"
export FFPROBE="$FFPROBE_BIN"
EOF
say "all dependencies ready"
